//! The pause menu dialogs (1.21.6+): welcome, travel, discoveries, outbreak and credits.

use super::{Credits, PackContext};
use serde_json::{json, Value};

const MENU: &str = "arnis:menu";

/// Translation key the world's resource pack maps to the logo glyph. Without the pack the
/// key falls back to nothing, so no missing-glyph box shows.
pub const BANNER_KEY: &str = "arnis.menu.banner";
pub const BANNER_FONT: &str = "arnis:banner";

fn text(s: impl Into<String>, color: &str) -> Value {
    json!({ "text": s.into(), "color": color })
}

fn message(contents: Value) -> Value {
    json!({ "type": "minecraft:plain_message", "contents": contents, "width": 300 })
}

fn back(with_menu: bool) -> Value {
    if with_menu {
        json!({ "label": "Back", "action": { "type": "show_dialog", "dialog": MENU } })
    } else {
        json!({ "label": "Close" })
    }
}

fn button(label: &str, tooltip: &str, action: Value) -> Value {
    json!({ "label": label, "tooltip": tooltip, "action": action })
}

fn run(command: &str) -> Value {
    json!({ "type": "run_command", "command": command })
}

fn open(url: &str) -> Value {
    json!({ "type": "open_url", "url": url })
}

fn show(dialog: &str) -> Value {
    json!({ "type": "show_dialog", "dialog": dialog })
}

/// The dialog the pause menu button opens.
pub fn menu(ctx: &PackContext) -> Value {
    let mut actions = Vec::new();
    if !ctx.destinations.is_empty() {
        actions.push(button(
            "Travel",
            "Jump to a landmark or back to spawn",
            show("arnis:travel"),
        ));
    }
    if ctx.has_discoveries() {
        actions.push(button(
            "Discoveries",
            "What there is to find here",
            show("arnis:discoveries"),
        ));
    }
    if ctx.extras.outbreak {
        actions.push(button(
            "Zombie Outbreak",
            "Restart, skip to night or stop",
            show("arnis:outbreak"),
        ));
    }
    actions.push(button(
        "Credits",
        "Where this world's data comes from",
        show("arnis:credits"),
    ));
    json!({
        "type": "minecraft:multi_action",
        "title": text(ctx.area.clone(), "gold"),
        "external_title": "Arnis",
        "body": [
            message(json!({
                "translate": BANNER_KEY,
                "fallback": "",
                "font": BANNER_FONT,
                "color": "white",
                "shadow_color": 0,
            })),
            message(json!([
                text("Welcome to ", "gray"),
                text(ctx.area.clone(), "white"),
                text(". This world was generated by Arnis from real map data.", "gray"),
            ])),
        ],
        "columns": 2,
        "actions": actions,
        "exit_action": { "label": "Back to Game" },
        // The game keeps running behind the action dialogs, so a trigger used here is
        // armed again before the next click.
        "pause": false,
    })
}

/// One button per destination; each sets the travel trigger the menu ticker acts on.
pub fn travel(ctx: &PackContext) -> Value {
    let actions: Vec<Value> = ctx
        .destinations
        .iter()
        .enumerate()
        .map(|(i, d)| {
            button(
                &d.name,
                &d.label,
                run(&format!("trigger arnis.tp set {}", i + 1)),
            )
        })
        .collect();
    json!({
        "type": "minecraft:multi_action",
        "title": text("Travel", "gold"),
        "body": [message(text("You land in the street next to it.", "gray"))],
        "columns": 2,
        "actions": actions,
        "exit_action": back(true),
        "pause": false,
    })
}

pub fn discoveries(ctx: &PackContext) -> Value {
    json!({
        "type": "minecraft:notice",
        "title": text("Discoveries", "gold"),
        "body": [
            message(text(
                format!(
                    "{} places to find: landmarks, museums, parks, stations and more. Walk up to one to discover it.",
                    ctx.places.len()
                ),
                "gray",
            )),
            message(text(
                format!("Your progress is in the Advancements screen (L), under {}.", ctx.area),
                "gray",
            )),
        ],
        "action": back(ctx.extras.pause_menu),
    })
}

pub fn outbreak(ctx: &PackContext) -> Value {
    json!({
        "type": "minecraft:multi_action",
        "title": text("Zombie Outbreak", "dark_red"),
        "body": [
            message(json!([
                text("Survive five nights in ", "gray"),
                text(ctx.area.clone(), "white"),
                text(". Zombies come every night, more each time, and on the fifth night a boss: Patient Zero.", "gray"),
            ])),
            message(text(
                "Loot buildings for gear and follow the smoke to a supply drop each morning. If you die, you come back as a zombie.",
                "gray",
            )),
        ],
        "columns": 3,
        "actions": [
            button("Restart", "Start again from day one", run("trigger arnis.ob.ctl set 1")),
            button("Skip to Night", "Bring on the next wave now", run("trigger arnis.ob.ctl set 2")),
            button("Stop", "End the outbreak and remove the zombies", run("trigger arnis.ob.ctl set 3")),
        ],
        "exit_action": back(ctx.extras.pause_menu),
        "pause": false,
    })
}

pub fn credits(ctx: &PackContext) -> Value {
    let lines: Vec<Value> = ctx
        .credits
        .lines()
        .into_iter()
        .map(|l| message(text(l, "gray")))
        .collect();
    json!({
        "type": "minecraft:multi_action",
        "title": text("Credits", "gold"),
        "body": lines,
        "columns": 2,
        "actions": [
            button("arnismc.com", "Arnis, free and open source", open("https://arnismc.com")),
            button("OpenStreetMap", "Map data © OpenStreetMap contributors", open("https://www.openstreetmap.org/copyright")),
        ],
        "exit_action": back(ctx.extras.pause_menu),
    })
}

impl Credits {
    /// One line per source this world was built from.
    pub fn lines(&self) -> Vec<String> {
        let mut lines = vec!["Generated with Arnis by Louis Erbkamm and contributors.".to_string()];
        if self.body_earth {
            lines.push(
                "Map data © OpenStreetMap contributors, available under the Open Database License."
                    .to_string(),
            );
            lines.push("Elevation © Mapterhorn (Copernicus GLO-30 © DLR/ESA, national mapping agencies), AWS Terrain Tiles and USGS 3DEP.".to_string());
            lines.push("Land cover © ESA WorldCover 2021 (CC BY 4.0). Climate: Köppen-Geiger, Beck et al. 2023. Ecoregions: RESOLVE 2017.".to_string());
        } else {
            lines.push(
                "Terrain from the NASA Planetary Data System: LRO LOLA (Moon) and MGS MOLA (Mars)."
                    .to_string(),
            );
        }
        if self.overture {
            lines.push("Extra buildings © Overture Maps Foundation (ODbL).".to_string());
        }
        if self.canopy {
            lines.push("Tree canopy © Meta and World Resources Institute (CC BY 4.0).".to_string());
        }
        if self.mapillary {
            lines.push("Street-level imagery © Mapillary contributors (CC BY-SA 4.0).".to_string());
        }
        lines.push("Not an official Minecraft product. Not approved by or associated with Mojang or Microsoft.".to_string());
        lines
    }
}
