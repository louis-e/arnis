//! Bavaria: the state survey's open laser scans and aerial photographs.
//!
//! Both come as 1 km tiles named by their south-west corner in ETRS89 / UTM 32
//! (EPSG:25832), the whole state in zone 32. Licence CC BY 4.0, attribution
//! "Bayerische Vermessungsverwaltung – www.geodaten.bayern.de".
//!
//! * Laser points: plain LAZ (LAS 1.2, point format 1), about 20 points per m²,
//!   classes 2 ground, 6 building, 20 object points (vegetation, cars, fences),
//!   22 cellar entrances. About 100 MB a tile; the server takes range requests but
//!   the points are not spatially indexed, so a tile is read whole.
//! * DOP20: 20 cm RGB GeoTIFF, LZW, tiled 256 x 256, one IFD, no overviews, so a
//!   tile's photo is read 51.2 m block by block with range requests.

