pub static BAVARIA: Source = Source {
    id: "bavaria",
    name: "Bavaria",
    grid: Grid::Fixed(Crs::Utm(32)),
    outline: &[OUTLINE],
    laser: Laser::Whole {
        locate: Locate::Urls(laser_url),
        tile_mb: 110,
    },
    photo: Photo::TiledTiff(photo_url),
    // Pinned per source until a calibration says otherwise: lawn returns about
    // 1770, paving about 1410 to 1480 in the 2022 campaign.
    intensity_defaults: (1450.0, 1600.0),
    classes: LaserClasses {
        ground: &[2],
        building: &[6],
        object: &[20],
        vegetation: &[],
        footprint: &[],
        unsorted: &[],
    },
    laser_plants: false,
    strict_pools: false,
    paving_brighter: false,
    attribution: "Bayerische Vermessungsverwaltung – www.geodaten.bayern.de (CC BY 4.0)",
};

fn laser_url(e_km: i32, n_km: i32) -> Vec<String> {
    vec![format!(
        "https://geodaten.bayern.de/odd_data/laser/{e_km}_{n_km}.laz"
    )]
}

fn photo_url(e_km: i32, n_km: i32) -> String {
    format!("https://download1.bayernwolke.de/a/dop20/data/32{e_km}_{n_km}.tif")
}
