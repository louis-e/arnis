pub static NETHERLANDS: Source = Source {
    id: "netherlands",
    name: "AHN",
    grid: Grid::Fixed(Crs::RdNew),
    outline: OUTLINE,
    laser: Laser::Copc {
        locate: Locate::Urls(laser_urls),
        mb_per_km2: 130,
        own_grid: false,
    },
    photo: Photo::Wms {
        url: "https://service.pdok.nl/hwh/luchtfotorgb/wms/v1_0",
        layer: "Actueel_orthoHR",
    },
    // From the photo calibration in Amersfoort (AHN5); a last resort.
    intensity_defaults: (2100.0, 2900.0),
    classes: LaserClasses {
        ground: &[2],
        building: &[6],
        object: &[1],
        vegetation: &[],
        footprint: &[],
        unsorted: &[],
    },
    laser_plants: true,
    strict_pools: false,
    paving_brighter: false,
    attribution: "AHN (CC0 / CC BY 4.0), Beeldmateriaal Nederland via PDOK (CC BY 4.0)",
};

fn laser_urls(e_km: i32, n_km: i32) -> Vec<String> {
    ["AHN5", "AHN4"]
        .iter()
        .map(|v| {
            format!(
                "https://fsn1.your-objectstorage.com/hwh-ahn/{v}_KM/01_LAZ/{v}_C_{}_{}.COPC.LAZ",
                e_km * 1000,
                n_km * 1000
            )
        })
        .collect()
}
