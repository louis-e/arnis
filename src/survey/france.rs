/// The LiDAR HD tiles over a rectangle, from the metadata WFS. Where a tile was
/// delivered twice, the later edition wins.
fn lookup(
    client: &reqwest::blocking::Client,
    _: &Sheet,
    (e0, n0, e1, n1): Rect,
) -> Result<TileUrls, String> {
    let url = format!(
        "https://data.geopf.fr/wfs/ows?SERVICE=WFS&VERSION=2.0.0&REQUEST=GetFeature\
         &TYPENAMES=IGNF_LIDAR-HD_METADONNEE:metadata&OUTPUTFORMAT=application/json\
         &SRSNAME=EPSG:2154&COUNT=1000&BBOX={e0},{n0},{e1},{n1},EPSG:2154"
    );
    let json = super::fetch::get_json(client, &url)?;
    let mut best: std::collections::HashMap<(i32, i32), (String, String)> = Default::default();
    for f in json["features"].as_array().into_iter().flatten() {
        let p = &f["properties"];
        let (Some(href), Some(nw)) = (p["url_npl"].as_str(), p["coordonnees_nw"].as_str()) else {
            continue;
        };
        let Some((x, y)) = nw.split_once('-') else {
            continue;
        };
        let (Ok(x), Ok(y)) = (x.parse::<i32>(), y.parse::<i32>()) else {
            continue;
        };
        let edition = p["date_edition"].as_str().unwrap_or("").to_string();
        // Named by the north-west corner; the grid names tiles by the south-west.
        let key = (x, y - 1);
        if best.get(&key).is_none_or(|(e, _)| *e < edition) {
            best.insert(key, (edition, href.to_string()));
        }
    }
    Ok(best.into_iter().map(|(k, (_, u))| (k, u)).collect())
}
