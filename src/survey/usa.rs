//! The United States: USGS 3D Elevation Program (3DEP) laser scans and NAIP
//! aerial photos.
//!
//! * 3DEP point clouds as Entwine point tiles on the public bucket
//!   `https://s3-us-west-2.amazonaws.com/usgs-lidar-public/<survey>/ept.json`,
//!   one octree per survey, reprojected to Web Mercator (EPSG:3857), heights in
//!   metres. Over 2,000 surveys from 2006 on, flown at 2 to 30 points per m²,
//!   many in leaf-off spring. Classes 1 unclassified, 2 ground, 6 building,
//!   3/4/5 vegetation where the survey sorts it out, 7/18 noise, 9 water,
//!   17 bridge; older surveys often leave buildings and plants in 1.
//! * The survey index: `https://usgs.entwine.io/boundaries/resources.geojson`
//!   (Hobu, refreshed daily, about 9 MB, 2.5 MB gzipped): one feature per
//!   survey with `name`, `count`, `url` (its `ept.json`) and a MultiPolygon of
//!   where its points are. Cached for a week. Each tile is read from the
//!   survey that covers it, newest first (the year is in the name: `_2018`, or
//!   `_B22` for fiscal 2022), then densest.
//! * NAIP: the latest statewide 60 cm (30 cm in places) photo through USGS's
//!   NAIP Plus WMS (`imagery.nationalmap.gov`), asked for in the area's NAD83
//!   UTM zone. Flown in summer, leaf-on.
//!
//! The grid is the NAD83 UTM zone of each area's middle. An area a few
//! hundred metres across reads 80 to 135 MB a square kilometre (Ann Arbor 2016
//! at 4 points per m² about 80, King County 2021 at 22 about 135): a survey's
//! nodes are small, and the level that reaches seven points a square metre is
//! read whole over the area. Public domain (U.S. Geological Survey, USDA Farm
//! Production and Conservation).

