//! Canada: Natural Resources Canada's CanElevation point clouds.
//!
//! * COPC files on the public bucket
//!   `https://canelevation-lidar-point-clouds.s3.ca-central-1.amazonaws.com/pointclouds_nuagespoints/<provider>/<project>/<tile>.copc.laz`,
//!   gathered from provinces, cities and federal surveys since about 2010: 362
//!   projects, 1 km tiles mostly (some 5 km or map sheets), 2 to 30 points per
//!   m² (Ottawa 2020 about 20). Each project in its NAD83(CSRS) UTM zone, named
//!   in the file's WKT record; heights CGVD2013 in metres. ASPRS classes: 2
//!   ground, 6 building, 3/4/5 vegetation where the project sorts it out, 1
//!   unclassified, 7/18 noise, 9 water.
//! * The tile index is NRCan's map service, queried by bounding box as GeoJSON:
//!   `https://maps-cartes.services.geo.ca/server_serveur/rest/services/NRCan/lidar_point_cloud_canelevation_en/MapServer/1/query`
//!   (fields `provider`, `project`, `tile_name`, `url`, a footprint polygon).
//!   Projects overlap; each tile is read from one, the newest (the year is in
//!   the project's name), and from all of that project's files over it, since
//!   their tiles need not follow the area's kilometres.
//! * No open national aerial photo: lawn and paving come from the ground
//!   returns' intensity, plants from the vegetation classes and the pulses.
//!
//! An area a few hundred metres across reads about 180 MB a square kilometre
//! (Ottawa 2020, 20 points per m², read at about 12): every file over the
//! area brings its own coarse levels.
//!
//! Buildings are often left in class 1 (Ottawa 2020 sorts only vegetation);
//! their roofs are then found from the pulses (see `laser::find_roofs`).
//!
//! Files in another grid than UTM in metres (one project, Montérégie 2020, is
//! in MTM) are not read. Open Government Licence – Canada.

