const INDEX: &str = "https://maps-cartes.services.geo.ca/server_serveur/rest/services/NRCan/lidar_point_cloud_canelevation_en/MapServer/1/query";

/// The files of the index's GeoJSON answer, one footprint each, grouped by
/// project.
pub fn parse_index(json: &serde_json::Value) -> Vec<Footprint> {
    json["features"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|f| {
            let p = &f["properties"];
            let (project, url) = (p["project"].as_str()?, p["url"].as_str()?);
            if !url.ends_with(".copc.laz") {
                return None;
            }
            let survey = format!("{}/{project}", p["provider"].as_str().unwrap_or(""));
            Footprint::new(url, &survey, survey_year(project), &f["geometry"], 0.0)
        })
        .collect()
}

fn lookup(
    client: &reqwest::blocking::Client,
    sheet: &Sheet,
    rect: Rect,
) -> Result<TileUrls, String> {
    let (e0, n0, e1, n1) = rect;
    let corners = [(e0, n0), (e0, n1), (e1, n0), (e1, n1)].map(|(e, n)| sheet.crs.inverse(e, n));
    let (mut s, mut w, mut n, mut e) = (f64::MAX, f64::MAX, f64::MIN, f64::MIN);
    for (lat, lon) in corners {
        s = s.min(lat);
        n = n.max(lat);
        w = w.min(lon);
        e = e.max(lon);
    }
    let url = format!(
        "{INDEX}?where=1%3D1&geometry={w:.6},{s:.6},{e:.6},{n:.6}&geometryType=esriGeometryEnvelope\
         &inSR=4326&spatialRel=esriSpatialRelIntersects&outFields=provider,project,tile_name,url\
         &returnGeometry=true&outSR=4326&f=geojson"
    );
    let json = super::fetch::get_json(client, &url)?;
    if let Some(err) = json.get("error") {
        return Err(format!("{INDEX}: {err}"));
    }
    Ok(choose(&parse_index(&json), sheet, rect))
}

